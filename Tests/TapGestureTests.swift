import Foundation

@main struct Tests {
    static func main() {
        var tap = TapGesture()
        assert(!tap.release(at: 0, modified: false))
        tap.press(at: 1, modified: false)
        assert(tap.release(at: 1.1, modified: false))
        tap.press(at: 1.12, modified: false)
        assert(tap.release(at: 1.2, modified: false), "Fast second tap must work")
        tap.press(at: 2, modified: false)
        assert(!tap.release(at: 2.5, modified: false))
        tap.press(at: 3, modified: false)
        tap.cancel()
        assert(!tap.release(at: 3.1, modified: false), "Fn chord must not switch")
        tap.press(at: 4, modified: true)
        assert(!tap.release(at: 4.1, modified: false))
        tap.press(at: 5, modified: false)
        assert(!tap.release(at: 5.1, modified: true))
        tap.press(at: 6, modified: false)
        tap.press(at: 6.3, modified: false)
        assert(!tap.release(at: 6.4, modified: false), "Repeated down cannot shorten hold")
        tap.press(at: 7, modified: false)
        tap.reset()
        assert(!tap.release(at: 7.1, modified: false), "Wake/reset cannot fire old gesture")
        var router = FnGestureRouter()
        _ = router.handle(hid: false, down: true, at: 10, modified: false)
        assert(router.handle(hid: false, down: false, at: 10.1, modified: false), "CG must work without HID events")
        _ = router.handle(hid: true, down: true, at: 11, modified: false)
        _ = router.handle(hid: false, down: true, at: 11.001, modified: false)
        assert(router.handle(hid: true, down: false, at: 11.1, modified: false))
        assert(!router.handle(hid: false, down: false, at: 11.101, modified: false), "One physical tap must not switch twice")
        _ = router.handle(hid: false, down: true, at: 11.15, modified: false)
        assert(router.handle(hid: false, down: false, at: 11.22, modified: false), "Distinct quick tap must switch")
        _ = router.handle(hid: true, down: true, at: 12, modified: false)
        _ = router.handle(hid: false, down: true, at: 12, modified: false)
        router.cancel()
        assert(!router.handle(hid: true, down: false, at: 12.1, modified: false))
        assert(!router.handle(hid: false, down: false, at: 12.1, modified: false))
        print("TapGesture and dual transport routing: all checks passed")
    }
}
